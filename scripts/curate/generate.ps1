param(
    [string]$HighCsv,      # verify.ps1 output for high-intensity.txt
    [string]$ModerateCsv,  # ... for moderate.txt (warm-up + recovery)
    [string]$CalmCsv,      # ... for calm.txt (cool-down)
    [string[]]$Exclude = @(),  # "genre|title" of wrong versions found by eye
    [string]$OutPath = "$PSScriptRoot/../../Packages/FourByFourCore/Sources/FourByFourCore/CuratedCatalog+Data.swift"
)
# Turns checked lists into CuratedCatalog+Data.swift. Rules per phase:
#   intervals:            energy >= 0.75 and a driving tempo (>= 120 BPM, or
#                         half-time that doubles to 150–215)
#   warm-up / recovery:   energy 0.45–0.97, not already an interval song
#                         (ReccoBeats rates loud rock / punk high even at a steady pace)
#   cool-down:            energy <= 0.75

$genreCase = @{ edm = 'edm'; dnb = 'drumAndBass'; trance = 'trance'; hardrock = 'hardRock'; punk = 'punk' }
$order = 'edm', 'dnb', 'trance', 'hardrock', 'punk'

function Read-Checked([string]$path) {
    $seen = @{}
    foreach ($row in Import-Csv $path) {
        if (-not $row.id -or -not $row.tempo) { continue }
        if ($Exclude -contains "$($row.genre)|$($row.title)") { continue }
        if ($seen.ContainsKey($row.id)) { continue }
        $seen[$row.id] = $true
        $row
    }
}

$intervalRows = @(Read-Checked $HighCsv | Where-Object {
    $t = [double]$_.tempo; $e = [double]$_.energy
    $e -ge 0.75 -and ($t -ge 120 -or ($t * 2 -ge 150 -and $t * 2 -le 215))
})
$intervalIDs = @($intervalRows | ForEach-Object id)
$moderateRows = @(Read-Checked $ModerateCsv | Where-Object {
    $e = [double]$_.energy
    $e -ge 0.45 -and $e -le 0.97 -and $intervalIDs -notcontains $_.id
})
$calmRows = @(Read-Checked $CalmCsv | Where-Object { [double]$_.energy -le 0.75 })

function Format-Block([string]$name, $rows) {
    $lines = @("    static let $($name): [MusicGenre: [CuratedTrack]] = [")
    foreach ($g in $order) {
        $lines += "        .$($genreCase[$g]): ["
        $genreRows = @($rows | Where-Object genre -eq $g)
        # Fewer than 5 songs is no list; the genre is then not offered for the phase.
        if ($genreRows.Count -lt 5) { $genreRows = @() }
        foreach ($r in $genreRows) {
            $a = $r.artist.Replace('\', '\\').Replace('"', '\"'); $t = $r.title.Replace('\', '\\').Replace('"', '\"')
            $lines += "            CuratedTrack(id: `"$($r.id)`", title: `"$t`", artist: `"$a`", tempo: $($r.tempo), energy: $($r.energy)),"
        }
        $lines += "        ],"
    }
    $lines += "    ]"
    return $lines
}

$swift = @(
    "// Generated by scripts/curate/generate.ps1 from hand-picked lists checked",
    "// against ReccoBeats ($(Get-Date -Format yyyy-MM-dd)): every track resolved to its Spotify ID",
    "// with the exact artist, tempo and energy filtered per phase. Regenerate",
    "// instead of editing.",
    "",
    "extension CuratedCatalog {"
) + (Format-Block 'highIntensity' $intervalRows) + @("") + (Format-Block 'moderate' $moderateRows) + @("") + (Format-Block 'calm' $calmRows) + @("}")
[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutPath), ($swift -join "`n") + "`n")

foreach ($set in @(@('intervals', $intervalRows), @('warm-up/recovery', $moderateRows), @('cool-down', $calmRows))) {
    $counts = $order | ForEach-Object { $g = $_; "$g $(@($set[1] | Where-Object genre -eq $g).Count)" }
    "$($set[0]): $($counts -join ', ')"
}
